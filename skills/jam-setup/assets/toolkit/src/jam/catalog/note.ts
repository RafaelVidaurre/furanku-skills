// What a reviewer reads beside a submitted step: what was asked for, what was done, with what,
// the numbers that matter and what to look at. Written for a person; record ids, hashes and
// paths stay in the run record. Pure.
import type { Budget } from "../config/schema.ts"
import type { ResolvedStep } from "../recipes/schema.ts"
import type { Run, StepRecord } from "../runs/schema.ts"

const NOTE_MAX = 5000
const ASK_MAX = 300
const BRIEF_MAX = 600

/** An id as a label: `three-quarter` reads "Three quarter". */
export const words = (id: string): string => id.replace(/[-_.]+/g, " ").replace(/^./, (first) => first.toUpperCase())

const count = (n: number): string => n.toLocaleString("en-US")
const plural = (n: number, one: string, many = `${one}s`): string => `${count(n)} ${n === 1 ? one : many}`

const madeWith = (run: Run, record: StepRecord): string | null => {
  const origin = record.provenance
  if (origin === undefined) return null
  if (origin.kind === "tool") return origin.tool === undefined ? null : `Made with ${origin.tool}.`
  if (origin.kind === "imported") return `Imported from ${origin.source ?? "outside the project"}.`
  // Only a job of this run can be described; another run's ledger is not at hand here.
  const job = origin.run === undefined ? run.jobs.find((candidate) => candidate.id === origin.job) : undefined
  const charge = job?.actual === undefined ? "" : `, ${count(job.actual)} ${job.unit}`
  return `Generated by ${origin.provider ?? "a provider"}${job === undefined ? "" : ` (${job.operation}${charge})`}.`
}

const measured = (record: StepRecord, budget: { readonly name: string; readonly budget: Budget } | null): string | null => {
  const metrics = record.metrics
  if (metrics?.triangles === undefined) return null
  const facts = [
    plural(metrics.triangles, "triangle"),
    ...(metrics.materials === undefined ? [] : [plural(metrics.materials, "material")]),
    ...(metrics.textureMiB === undefined ? [] : [`${metrics.textureMiB.toFixed(2)} MiB of textures`])
  ]
  const limit = budget === null
    ? ""
    : ` Budget ${budget.name} allows ${count(budget.budget.triangles.max)} triangles, ${plural(budget.budget.maxMaterials, "material")} and ${budget.budget.maxTextureMiB} MiB.`
  return `Measured: ${facts.join(", ")}.${limit}`
}

const imageSizes = (record: StepRecord): string | null => {
  const sizes = record.files.flatMap((file) => (file.size === undefined ? [] : [`${file.size[0]} × ${file.size[1]}`]))
  if (sizes.length === 0) return null
  const distinct = [...new Set(sizes)]
  return distinct.length === 1 ? `${plural(sizes.length, "image")} at ${distinct[0]} px.` : `Image sizes: ${distinct.join(", ")} px.`
}

export interface NoteInput {
  readonly run: Run
  readonly recipeTitle: string
  readonly step: ResolvedStep
  readonly record: StepRecord
  readonly budget: { readonly name: string; readonly budget: Budget } | null
  /** The brief's text, when it can be read. */
  readonly brief: string | null
  /** Labels of the parts to decide, and of the supporting evidence shown with them. */
  readonly parts: ReadonlyArray<string>
  readonly evidence: ReadonlyArray<string>
}

/** The question a reviewer answers and the brief beside it. */
export const reviewNote = (input: NoteInput): { readonly ask: string; readonly brief: string } => {
  const { record, run, step } = input
  const brief = input.brief?.trim() ?? ""
  const asked = brief === "" ? [] : ["**Asked for**", "", ...(brief.length > BRIEF_MAX ? `${brief.slice(0, BRIEF_MAX).trimEnd()}…` : brief).split("\n").map((line) => `> ${line}`), ""]
  const facts = [madeWith(run, record), measured(record, input.budget), imageSizes(record)].filter((line): line is string => line !== null)
  const note = [
    `**${step.title}** of \`${run.id}\`${run.n > 1 ? ` (attempt ${run.n})` : ""}, ${input.recipeTitle}.`,
    "",
    ...asked,
    "**Done**",
    "",
    record.note.trim(),
    "",
    ...facts.map((line) => `- ${line}`),
    ...(input.evidence.length > 0 ? ["", `**Supporting evidence:** ${input.evidence.join(", ")}.`] : [])
  ].join("\n").trimEnd()
  const ask = `Accept, change or reject: ${input.parts.join(", ")}.`
  return {
    ask: ask.length > ASK_MAX ? `${ask.slice(0, ASK_MAX - 2)}….` : ask,
    brief: note.length > NOTE_MAX ? `${note.slice(0, NOTE_MAX - 1)}…` : note
  }
}
